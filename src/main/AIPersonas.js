function getPersona(id) {
  return AI_PERSONAS.find((p) => p.id === id) || AI_PERSONAS[0];
}

/** 解析最终 system 提示词；custom 且有文本时用用户文本（附基础护栏），否则回退默认。 */
function resolveDeepReadSystem(persona) {
  const p = getPersona(persona?.id);
  if (p.id === 'custom') {
    const text = String(persona?.custom || '').trim();
    if (text) return `${text}\n\n（通用要求：${DEEP_READ_BASE}）`;
    return getPersona('scholar').system;
  }
  return p.system;
}

module.exports = { AI_PERSONAS, getPersona, resolveDeepReadSystem };
